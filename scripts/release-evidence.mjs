#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import path from "node:path";
import { pathToFileURL } from "node:url";

const execFileAsync = promisify(execFile);

async function run(command, args) {
  const result = await execFileAsync(command, args, { stdio: "inherit" });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
}

async function main() {
  const argv = process.argv.slice(2);
  const index = argv.indexOf("--output-dir");
  const outputDir = path.resolve(index >= 0 && argv[index + 1] ? argv[index + 1] : "target/release-evidence");
  await mkdir(outputDir, { recursive: true });
  await run("npm", ["run", "build"]);
  await run("node", ["scripts/report-web-bundle.mjs", "--output", path.join(outputDir, "bundle.json")]);
  await run("node", ["scripts/benchmark-recipe-scroll.mjs", "--output", path.join(outputDir, "benchmark.json")]);
  await run("node", ["scripts/check-release-budgets.mjs", "--bundle", path.join(outputDir, "bundle.json"), "--benchmark", path.join(outputDir, "benchmark.json")]);
  const bundle = JSON.parse(await readFile(path.join(outputDir, "bundle.json"), "utf8"));
  const benchmark = JSON.parse(await readFile(path.join(outputDir, "benchmark.json"), "utf8"));
  const markdown = [
    "# Release evidence",
    "",
    "Generated by `npm run perf:release` from the checked-in bundle report and five-pass visual benchmark.",
    "",
    "## Baseline",
    "",
    "- Initial route gzip: `" + bundle.initialRouteGzipBytes + " bytes`.",
    "- Frame gap: median `"+ benchmark.p95FrameGap.median.toFixed(1) + "ms, p95 " + benchmark.p95FrameGap.p95.toFixed(1) + "ms`.",
    "- Visible cover invariants: empty `"+ benchmark.maxEmptyCovers + "`, blank `"+ benchmark.maxBlankCovers + "`, error `"+ benchmark.maxErrorCovers + "`, incomplete `"+ benchmark.maxIncompleteImages + "`, synthetic `"+ benchmark.maxSyntheticImages + "`.",
    "- Recipe open: `"+ benchmark.recipeOpen.viewVisibleMs + "ms`.",
    "- Recipe search: `"+ benchmark.recipeSearch.inputToResultsMs + "ms` to `"+ benchmark.recipeSearch.resultCount + "` result.",
    "",
    "## Release checklist",
    "",
    "- [ ] Run `nix-shell --run 'npx playwright install chromium'` once on a fresh NixOS checkout.",
    "- [ ] Run `nix-shell --run 'npm run perf:release'`.",
    "- [ ] Confirm `release budgets passed.` and attach `bundle.json` plus `benchmark.json` to release evidence.",
    "- [ ] Run `npm run typecheck`, `npm test`, and the visual suite.",
    ""
  ].join("\n");
  await writeFile(path.join(outputDir, "README.md"), markdown, "utf8");
  console.log("release evidence complete: " + outputDir);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error("release evidence failed: " + (error instanceof Error ? error.message : String(error)));
    process.exitCode = 1;
  });
}
